<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Http\Client\ConnectionException;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Http;
use RuntimeException;

class AddMaterialIcon extends Command
{
    protected $signature = 'icon:add
        {names* : Material Symbols names, e.g. arrow_forward or check-circle}
        {--force : Overwrite existing icon components}
        {--path= : Output directory (defaults to resources/views/components/icon)}';

    protected $description = 'Download Material Symbols Rounded SVGs and generate <x-icon.*> Blade components';

    private const SOURCE = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/%s/%s/24px.svg';

    public function handle(): int
    {
        $directory = $this->option('path') ?: resource_path('views/components/icon');
        File::ensureDirectoryExists($directory);
        $failed = false;

        foreach ($this->argument('names') as $input) {
            $name = str_replace('-', '_', strtolower(trim($input)));
            if (! preg_match('/^[a-z0-9_]+$/', $name) || $name === 'index') {
                $this->error("Invalid icon name: {$input}");
                $failed = true;

                continue;
            }

            $file = $directory.DIRECTORY_SEPARATOR.str_replace('_', '-', $name).'.blade.php';
            if (File::exists($file) && ! $this->option('force')) {
                $this->line("Skipped {$name} (exists; use --force to overwrite)");

                continue;
            }

            try {
                $outlined = $this->paths($name, 'default');
                $filled = $this->paths($name, 'fill1', optional: true) ?? $outlined;
            } catch (RuntimeException $e) {
                $this->error($e->getMessage());
                $failed = true;

                continue;
            }

            File::put($file, $this->component($name, $outlined, $filled));
            $this->info("Created {$name} → <x-icon.".str_replace('_', '-', $name).' />');
        }

        return $failed ? self::FAILURE : self::SUCCESS;
    }

    /** @return list<string>|null */
    private function paths(string $name, string $variant, bool $optional = false): ?array
    {
        try {
            // IPv4 avoids long connect timeouts on networks with broken IPv6 routes.
            $response = Http::withOptions(['force_ip_resolve' => 'v4'])->connectTimeout(10)->timeout(20)->retry(3, 500, throw: false)->get(sprintf(self::SOURCE, $name, $variant));
        } catch (ConnectionException $e) {
            throw new RuntimeException("Could not download {$name} ({$variant}): {$e->getMessage()}");
        }

        if (! $response->successful()) {
            // Only a genuine 404 means "no filled variant"; other failures must not silently fall back.
            if ($optional && $response->status() === 404) {
                return null;
            }
            throw new RuntimeException("Icon not found upstream: {$name} (HTTP {$response->status()})");
        }

        preg_match_all('/<path[^>]*\sd="([^"]+)"/', $response->body(), $matches);
        if ($matches[1] === []) {
            throw new RuntimeException("No path data found for {$name} ({$variant})");
        }

        return $matches[1];
    }

    /** @param list<string> $outlined @param list<string> $filled */
    private function component(string $name, array $outlined, array $filled): string
    {
        $render = fn (array $paths) => implode("\n", array_map(fn ($d) => "        <path d=\"{$d}\"/>", $paths));

        return <<<BLADE
{{-- Material Symbols Rounded: {$name} (generated by `php artisan icon:add`) --}}
@props(['filled' => false])
<svg {{ \$attributes->class(['size-6 shrink-0'])->merge(['aria-hidden' => 'true', 'focusable' => 'false']) }} xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" fill="currentColor">
    @if (\$filled)
{$render($filled)}
    @else
{$render($outlined)}
    @endif
</svg>

BLADE;
    }
}
